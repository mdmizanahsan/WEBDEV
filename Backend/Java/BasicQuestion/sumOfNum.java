// Find the sum of numbers from 1 to n 
package Backend.Java.BasicQuestion;

public class sumOfNum {
      public static void main(String[] args) {
        int n = 5;

        int sum = 0;

        for(int i = 0; i <= n; i++){
            sum += i;

        }
           System.out.println("Sum = " +sum);

      }
}
